import type { Filters, Row } from "@/types/models";
import { downloadCsv } from "@/utils/csv";

export function exportRows(title: string, rows: Row[], filters: Filters) {
  downloadCsv(
    `${title}-${filters.start}-${filters.end}`,
    [
      "Demo data",
      "Period start",
      "Period end",
      "Shift",
      "ID",
      "Name",
      "Location",
      "BMC",
      "Society",
      "Demo contact",
      "Registered cows",
      "Farmers",
      "Milk (L)",
      "Morning (L)",
      "Evening (L)",
      "Status",
      "Confirmed zero shifts",
      "Missing record shifts",
      "Pending shifts",
      "Affected farmer-days",
      "Affected farmers",
      "Last delivery",
      "Last delivery scope",
      "Pattern",
    ],
    rows.map((r) => [
      "Yes",
      filters.start,
      filters.end,
      filters.shift,
      r.id,
      r.name,
      r.location,
      r.bmc,
      r.society,
      r.contact,
      r.cows,
      r.farmers,
      (r.ml / 1000).toFixed(3),
      (r.morning / 1000).toFixed(3),
      (r.evening / 1000).toFixed(3),
      r.status,
      r.zero,
      r.missing,
      r.pending,
      r.missedDays,
      r.affected,
      r.lastDelivery || "None in stated scope",
      r.lastDeliveryScope,
      r.pattern,
    ]),
  );
}
